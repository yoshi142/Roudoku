import re
SPACE=re.compile(r'宇宙|天文|惑星|ブラックホール|銀河(?!鉄道)|太陽系|ビッグバン|ボイジャー|NASA|JAXA|星雲|恒星|月面|火星|異星人|宇宙人|UFO|ロケット|探査機|天体|系外')
AI=re.compile(r'(?<![A-Za-z])AI(?![A-Za-z])|人工知能|ChatGPT|生成AI|Gemini|Claude')
LIT=re.compile(r'宮沢|宮澤|賢治|芥川|太宰|夏目|漱石|鴎外|鷗外|中島敦|新美|南吉|未明|梶井|安吾|乱歩|夢野|鏡花|一葉|八雲|有島|菊池寛|藤村|中原中也|高村|啄木|与謝野|晶子|朔太郎|堀辰雄|綺堂|芙美子|百合子|織田作|海野十三|寅彦|谷崎|荷風|独歩|二葉亭|子規|白秋|童話|グリム|アンデルセン|イソップ|青空文庫|古典|枕草子|平家|徒然草|方丈記|竹取|源氏|古事記|昔話|民話|名作|文学|小説|詩集|走れメロス|銀河鉄道|星の王子|ルナール|チェーホフ|ポー|ドイル|ホームズ|モーパッサン|O・ヘンリー|小酒井|久生十蘭|岡本かの子|牧野信一|横光|佐藤春夫|室生|山本周五郎|吉川英治|直木')
def genre(t):
    t=t or ''
    if AI.search(t): return 'AI'
    if SPACE.search(t) and not LIT.search(t): return '宇宙'
    if LIT.search(t): return '文学'
    return 'その他'
