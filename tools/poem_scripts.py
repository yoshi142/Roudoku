def lines(t):
    raw=[l.rstrip('\r').strip('\u3000 ') for l in t.split('\n')]
    # 青空文庫では行ごとに空行が入ることが多い。空行の最頻値を「行間」とみなし、それより多い空行を連の切れ目にする
    gaps=[]; g=0
    for l in raw:
        if l: 
            if gaps or g: gaps.append(g)
            g=0
        else: g+=1
    base=max(set(gaps), key=gaps.count) if gaps else 0
    out=[]; blank=0
    for l in raw:
        if not l: blank+=1; continue
        if blank>base and out: out[-1]=out[-1].rstrip('／')+'／／'
        out.append(l+'／'); blank=0
    return '\n'.join(out)
def modern(t,table):
    for a,b in table: t=t.replace(a,b)
    return t
